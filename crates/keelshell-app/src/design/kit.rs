//! The only mapping from application tokens to GPUI Kit component colors.

use super::{ComponentTokens, Palette};
use gpui_kit::{App, component::Theme, px, rgb};

pub(super) fn install(p: Palette, shape: ComponentTokens, cx: &mut App) {
    Theme::update(cx, |theme| {
        theme.radius = px(shape.control_radius);
        theme.radius_lg = px(shape.panel_radius);
        theme.font_size = px(14.);
        let c = &mut theme.colors;
        c.background = rgb(p.surface).into();
        c.foreground = rgb(p.text).into();
        c.border = rgb(p.border).into();
        c.input = rgb(p.field_border).into();
        c.muted = rgb(p.canvas).into();
        c.muted_foreground = rgb(p.muted).into();
        c.accent = rgb(p.surface_hover).into();
        c.accent_foreground = rgb(p.accent).into();
        c.ring = rgb(p.focus).into();
        c.caret = rgb(p.focus).into();
        c.selection = rgb(p.selected).into();
        c.primary = rgb(p.primary).into();
        c.primary_hover = rgb(p.primary_hover).into();
        c.primary_active = rgb(p.primary_active).into();
        c.primary_foreground = rgb(p.primary_text).into();
        c.button_primary = c.primary;
        c.button_primary_hover = c.primary_hover;
        c.button_primary_active = c.primary_active;
        c.button_primary_foreground = c.primary_foreground;
        c.button = rgb(p.surface).into();
        c.button_foreground = rgb(p.text).into();
        c.button_hover = rgb(p.surface_hover).into();
        c.button_active = rgb(p.surface_active).into();
        c.secondary = rgb(p.toolbar).into();
        c.secondary_foreground = rgb(p.text).into();
        c.secondary_hover = rgb(p.surface_hover).into();
        c.secondary_active = rgb(p.surface_active).into();
        c.button_secondary = c.secondary;
        c.button_secondary_foreground = c.secondary_foreground;
        c.button_secondary_hover = c.secondary_hover;
        c.button_secondary_active = c.secondary_active;
        c.danger = rgb(p.danger).into();
        c.danger_hover = c.danger;
        c.danger_active = c.danger;
        c.danger_foreground = rgb(p.status_text).into();
        c.button_danger = c.danger;
        c.button_danger_hover = c.danger_hover;
        c.button_danger_active = c.danger_active;
        c.button_danger_foreground = c.danger_foreground;
        c.success = rgb(p.success).into();
        c.success_hover = c.success;
        c.success_active = c.success;
        c.success_foreground = rgb(p.status_text).into();
        c.button_success = c.success;
        c.button_success_hover = c.success_hover;
        c.button_success_active = c.success_active;
        c.button_success_foreground = c.success_foreground;
        c.warning = rgb(p.warning).into();
        c.warning_hover = c.warning;
        c.warning_active = c.warning;
        c.warning_foreground = rgb(p.status_text).into();
        c.button_warning = c.warning;
        c.button_warning_hover = c.warning_hover;
        c.button_warning_active = c.warning_active;
        c.button_warning_foreground = c.warning_foreground;
        c.info = c.primary;
        c.info_hover = c.primary_hover;
        c.info_active = c.primary_active;
        c.info_foreground = c.primary_foreground;
        c.button_info = c.info;
        c.button_info_hover = c.info_hover;
        c.button_info_active = c.info_active;
        c.button_info_foreground = c.info_foreground;
        c.link = rgb(p.accent).into();
        c.link_hover = rgb(p.focus).into();
        c.link_active = rgb(p.primary_active).into();
        c.popover = rgb(p.surface).into();
        c.popover_foreground = rgb(p.text).into();
        c.list = rgb(p.surface).into();
        c.list_head = rgb(p.toolbar).into();
        c.list_even = rgb(p.surface).into();
        c.list_hover = rgb(p.surface_hover).into();
        c.list_active = rgb(p.surface_active).into();
        c.list_active_border = rgb(p.focus).into();
        c.table = rgb(p.surface).into();
        c.table_head = rgb(p.toolbar).into();
        c.table_head_foreground = rgb(p.muted).into();
        c.table_foot = rgb(p.toolbar).into();
        c.table_foot_foreground = rgb(p.muted).into();
        c.table_even = rgb(p.surface).into();
        c.table_hover = rgb(p.surface_hover).into();
        c.table_active = rgb(p.surface_active).into();
        c.table_active_border = rgb(p.focus).into();
        c.table_row_border = rgb(p.border).into();
        c.tab = rgb(p.toolbar).into();
        c.tab_foreground = rgb(p.muted).into();
        c.tab_active = rgb(p.surface).into();
        c.tab_active_foreground = rgb(p.text).into();
        c.tab_bar = rgb(p.toolbar).into();
        c.tab_bar_segmented = rgb(p.canvas).into();
        c.sidebar = rgb(p.sidebar).into();
        c.sidebar_foreground = rgb(p.text).into();
        c.sidebar_border = rgb(p.border).into();
        c.sidebar_accent = rgb(p.selected).into();
        c.sidebar_accent_foreground = rgb(p.accent).into();
        c.sidebar_primary = c.primary;
        c.sidebar_primary_foreground = c.primary_foreground;
        c.title_bar = rgb(p.toolbar).into();
        c.title_bar_border = rgb(p.border).into();
        c.status_bar = rgb(p.toolbar).into();
        c.status_bar_border = rgb(p.border).into();
        c.scrollbar = rgb(p.canvas).into();
        c.scrollbar_thumb = rgb(p.field_border).into();
        c.scrollbar_thumb_hover = rgb(p.muted).into();
        c.group_box = rgb(p.toolbar).into();
        c.group_box_foreground = rgb(p.text).into();
        c.accordion = rgb(p.surface).into();
        c.description_list_label = rgb(p.toolbar).into();
        c.description_list_label_foreground = rgb(p.muted).into();
        c.drag_border = rgb(p.focus).into();
        c.drop_target = rgb(p.surface_active).into();
        c.progress_bar = rgb(p.primary).into();
        c.slider_bar = rgb(p.primary).into();
        c.slider_thumb = rgb(p.surface).into();
        c.switch = rgb(p.field_border).into();
        c.switch_thumb = rgb(p.surface).into();
        c.skeleton = rgb(p.border).into();
        c.window_border = rgb(p.border).into();
    });
}
